#!/usr/bin/env node
/**
 * Turns the Markdown items in src/content/items into SQL you can paste into Supabase,
 * so your existing archive becomes OFFARCHIVE.'s own listings in the marketplace.
 *
 *   npm run seed:export   →  writes supabase/seed.sql
 *
 * Run the SQL *after* you've signed up on the site and made yourself admin
 * (docs/SUPABASE.md, step 6). Listings are attached to the first admin account.
 * Local photos aren't uploaded: re-add them from the edit page, or upload to the bucket.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import yaml from 'js-yaml';

const DIR = 'src/content/items';
const q = (v) => (v === null || v === undefined || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`);

const files = (await readdir(DIR)).filter((f) => f.endsWith('.md') && !f.startsWith('_')).sort();
const rows = [];
for (const file of files) {
  const raw = await readFile(join(DIR, file), 'utf8');
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!match) continue;
  const d = yaml.load(match[1]);
  if (d.draft) continue;
  const slug = file.replace(/\.md$/, '');
  const listed = d.listed instanceof Date ? d.listed.toISOString() : new Date(d.listed).toISOString();
  rows.push(
    `  (${[
      q(slug),
      q(d.title),
      q(d.category),
      Number(d.price),
      q(String(d.size)),
      q(d.condition),
      `${q(d.status ?? 'available')}::public.listing_status`,
      q(d.brand),
      q(match[2].trim()),
      q(d.fit),
      q(d.flaws ?? 'None noted. See photos.'),
      `${q(JSON.stringify(d.measurements ?? {}))}::jsonb`,
      q(d.art ?? 'tee'),
      d.featured ? 'true' : 'false',
      `${q(listed)}::timestamptz`,
    ].join(', ')})`,
  );
}

const sql = `-- Generated by \`npm run seed:export\` from src/content/items (${rows.length} items).
-- Paste into Supabase → SQL Editor AFTER making yourself admin. Safe to re-run (skips existing slugs).
insert into public.listings
  (seller_id, slug, title, category, price, size, condition, status, brand, description, fit, flaws, measurements, art, featured, listed_at)
select
  (select id from public.profiles where role = 'admin' order by created_at limit 1),
  v.*
from (values
${rows.join(',\n')}
) as v(slug, title, category, price, size, condition, status, brand, description, fit, flaws, measurements, art, featured, listed_at)
where exists (select 1 from public.profiles where role = 'admin')
on conflict (slug) do nothing;
`;

await writeFile('supabase/seed.sql', sql);
console.log(`✓ Wrote supabase/seed.sql with ${rows.length} listings.`);
